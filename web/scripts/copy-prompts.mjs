// Prebuild step: copies prompts/*.md and prompts/kitchen-profile.default.json (the single source, shared with the
// Python engine) into web/generated/, plus data/open/aliases.json (food names in English, used by the prompt
// rendering like smartbite_engine/names.py), data/open/inspiration/dishes.json (real dishes for the Idea agent, picked
// like smartbite_engine/inspiration.py) and a slim copy of data/open/packs/packs.json (food -> typical pack size, for
// the recipe prompt's pack hints; ODbL 1.0, see data/open/packs/LICENSE), and writes web/generated/index.js so the
// app and the tests import plain JS.
// Runs before build, dev and test (package.json), so the web app never reads outside web/ at runtime.
// web/generated/ is a build output: gitignored, rebuilt by this script.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const WEB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = path.resolve(WEB, "..", "prompts");
const OUT = path.join(WEB, "generated");
const DATA = path.resolve(WEB, "..", "data", "open");
const ALIASES = path.join(DATA, "aliases.json");
const DISHES = path.join(DATA, "inspiration", "dishes.json");
const PACKS = path.join(DATA, "packs", "packs.json");
const DISH_FIELDS = ["name", "cuisine", "style", "core", "method"];

const templates = {};
fs.mkdirSync(path.join(OUT, "prompts"), { recursive: true });
for (const file of fs.readdirSync(SOURCE).filter((f) => f.endsWith(".md")).sort()) {
  const text = fs.readFileSync(path.join(SOURCE, file), "utf8");
  fs.writeFileSync(path.join(OUT, "prompts", file), text);
  templates[file.replace(/\.md$/, "")] = text;
}
const profileText = fs.readFileSync(path.join(SOURCE, "kitchen-profile.default.json"), "utf8");
fs.writeFileSync(path.join(OUT, "prompts", "kitchen-profile.default.json"), profileText);

const aliasesText = fs.existsSync(ALIASES) ? fs.readFileSync(ALIASES, "utf8") : '{"foods": [], "aliases": {}}';
fs.writeFileSync(path.join(OUT, "aliases.json"), aliasesText);
const aliases = JSON.parse(aliasesText);

const dishesText = fs.existsSync(DISHES) ? fs.readFileSync(DISHES, "utf8") : '{"dishes": []}';
fs.writeFileSync(path.join(OUT, "dishes.json"), dishesText);
const dishes = (JSON.parse(dishesText).dishes || []).map((d) => Object.fromEntries(DISH_FIELDS.map((k) => [k, d[k]])));

// Only what the pack hints need: sold_by, the default size and, for eggs, the units per pack
const packFoods = fs.existsSync(PACKS) ? JSON.parse(fs.readFileSync(PACKS, "utf8")).foods || {} : {};
const packSizes = Object.fromEntries(Object.entries(packFoods).map(([food, e]) => [food,
  { sold_by: e.sold_by, default_grams: e.default_grams ?? null, ...(e.units_per_pack != null && { units_per_pack: e.units_per_pack }) }]));
fs.writeFileSync(path.join(OUT, "pack-sizes.json"), JSON.stringify({
  note: "Slim copy of data/open/packs/packs.json made by scripts/copy-prompts.mjs: typical pack size per food.",
  license: "ODbL 1.0, built from Open Food Facts (https://world.openfoodfacts.org). See data/open/packs/LICENSE and SOURCES.md.",
  foods: packSizes }, null, 1) + "\n");

const js = `// Generated by scripts/copy-prompts.mjs from prompts/. Do not edit: change prompts/ and rebuild.
export const TEMPLATES = ${JSON.stringify(templates, null, 2)};
export const DEFAULT_PROFILE = ${JSON.stringify(JSON.parse(profileText), null, 2)};
export const ALIASES = ${JSON.stringify({ foods: aliases.foods || [], aliases: aliases.aliases || {} })};
export const DISHES = ${JSON.stringify(dishes)};
// Typical pack sizes: ODbL 1.0, built from Open Food Facts (data/open/packs/LICENSE)
export const PACK_SIZES = ${JSON.stringify(packSizes)};
`;
fs.writeFileSync(path.join(OUT, "index.js"), js);
console.log(`copy-prompts: ${Object.keys(templates).join(", ")}, the default Kitchen Profile, ${(aliases.foods || []).length} food names, ` +
  `${dishes.length} dishes and ${Object.keys(packSizes).length} pack sizes -> generated/`);
