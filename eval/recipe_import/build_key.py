"""Build the paste-a-recipe import eval set from the hand-written answer key.

Reads eval/recipe_import/key.json (foods and amounts per pasted recipe), portions.json (USDA SR Legacy household weights) and
pastes/<id>.txt (the text a user pastes), and writes:
  cases.json      one case per recipe: the paste and, per food, the accepted app names and the gram window that passes
  answer-key.md   the same as tables, for review by hand

Grams are for the WHOLE recipe as written, not per serving: the model returns totals and code divides by the servings.
Tolerances (key.json): weight given in the text +-10 %, household measures (cups, spoons, "1 onion") +-25 %, ranges
from 10 % under the low end to 10 % over the high end. Volumes of liquids that are not in portions.json (coconut
yogurt, wine) count 1 g per ml. Eggs are scored in units, exactly. Run: python -m eval.recipe_import.build_key (no network).
"""
import json
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

HERE = Path(__file__).parent
LB_G = 453.59237


def whole(x):
    """Whole grams, halves rounded up (8.5 -> 9), for the review table."""
    return Decimal(str(x)).quantize(Decimal("1"), rounding=ROUND_HALF_UP)

OZ_G = 28.349523125


def base_grams(spec, portions):
    """Expected grams for one amount spec (no tolerance)."""
    if "household" in spec:
        return portions[spec["household"]]["grams"] * spec["count"]
    if "weight" in spec:
        w = spec["weight"]
        return w.get("g", 0) + w.get("kg", 0) * 1000 + w.get("lb", 0) * LB_G + w.get("oz", 0) * OZ_G
    if "volume" in spec:
        return spec["volume"]["ml"] * 1.0
    raise ValueError(f"unknown amount {spec}")


def window(amount, portions, tol):
    """(kind, expected, low, high) in grams, or eggs in units; None when only presence is checked."""
    if amount is None:
        return None
    if "eggs" in amount:
        return ("eggs", amount["eggs"], amount["eggs"], amount["eggs"])
    if "range" in amount:
        lo, hi = (base_grams(s, portions) for s in amount["range"])
        m = tol["range_margin"]
        return ("range", (lo + hi) / 2, lo * (1 - m), hi * (1 + m))
    g = base_grams(amount, portions)
    t = tol["household"] if "household" in amount else tol["weight"]
    return ("household" if "household" in amount else "weight", g, g * (1 - t), g * (1 + t))


def build():
    key = json.loads((HERE / "key.json").read_text())
    portions = json.loads((HERE / "portions.json").read_text())["portions"]
    tol = key["tolerances"]
    cases, md = [], ["# Paste a recipe: answer key (draft for review)", "",
                     "Generated by `eval/recipe_import/build_key.py` from `key.json` and `portions.json`. Grams are for the whole "
                     "recipe. Pass window: weight in the text +-10 %, cups/spoons/pieces +-25 %, ranges 10 % past each end. "
                     "Eggs in units. `UNKNOWN (leek)` = not in the app's food list, kept under its own name, which must "
                     "contain one of the words in brackets. "
                     "Not required = reported only (salt, spices, dried herbs).", ""]
    for c in key["cases"]:
        paste = (HERE / "pastes" / f"{c['id']}.txt").read_text()
        foods = []
        for f in c["foods"]:
            w = window(f["amount"], portions, tol)
            exact = None if w is None else {"expected": w[1], "low": w[2], "high": w[3]}
            if "UNKNOWN" in f["accept"] and not f.get("unknown_names"):
                raise SystemExit(f"{c['id']}: {f['line']!r} accepts UNKNOWN but has no unknown_names")
            foods.append({"line": f["line"], "accept": f["accept"], "unknown_names": f.get("unknown_names", []),
                          "pantry": bool(f.get("pantry")), "_exact": exact,
                          "required": f["required"], "optional": bool(f.get("optional")),
                          "check": None if w is None else {"kind": w[0], "expected": round(w[1], 1),
                                                           "low": round(w[2], 1), "high": round(w[3], 1)}})
        cases.append({"id": c["id"], "lang": c["lang"], "paste": paste, "servings": c["servings"],
                      "servings_also_ok": c.get("servings_also_ok", []), "foods": foods,
                      "must_not_include": c["must_not_include"]})
        sv = c["servings"] if c["servings"] is not None else "not in the text (app asks)"
        md += [f"## {c['id']}", "", f"Tests: {c['why']}.", "", f"Servings: {sv}"
               + (f" (also passes: {', '.join('none' if x is None else str(x) for x in c.get('servings_also_ok', []))})"
                  if c.get("servings_also_ok") else ""), "",
               "| Line in the paste | App food | Grams (whole recipe) | Pass window | Required |", "|---|---|---|---|---|"]
        for f in foods:
            ch, ex = f["check"], f.pop("_exact")
            if ch is None:
                g, win = "presence only", ""
            elif ch["kind"] == "eggs":
                g, win = f"{ch['expected']:g} eggs", "exact"
            else:
                g, win = f"{whole(ex['expected'])}", f"{whole(ex['low'])} to {whole(ex['high'])}"
            req = "yes" if f["required"] else ("optional" if f["optional"] else "no")
            want = " or ".join(f"UNKNOWN ({' / '.join(f['unknown_names'])})" if a == "UNKNOWN" else a for a in f["accept"])
            md.append(f"| {f['line']} | {want} | {g} | {win} | {req} |")
        if c["must_not_include"]:
            md += ["", f"Must not add: {', '.join(c['must_not_include'])}."]
        md.append("")
    (HERE / "cases.json").write_text(json.dumps({"note": "Built by build_key.py; do not edit by hand.", "cases": cases},
                                                ensure_ascii=False, indent=1) + "\n")
    (HERE / "answer-key.md").write_text("\n".join(md))
    return cases


if __name__ == "__main__":
    out = build()
    print(f"{len(out)} cases, {sum(len(c['foods']) for c in out)} food lines, "
          f"{sum(1 for c in out for f in c['foods'] if f['required'])} required")
